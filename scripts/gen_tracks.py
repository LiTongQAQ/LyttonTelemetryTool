"""Builds apps/dash-app/tracks/track_data.inc from the bundled track data.

Sources (both in third_party/, see their LICENSE files):
  - racetrack-database (TUMFTM, LGPL-3.0): centre line + left/right track widths, ~5 m spacing, x/y in metres.
  - f1-circuits (bacinger, MIT): centre line only, as lon/lat (GeoJSON). Used for the circuits TUMFTM lacks; the
    width is a typical value per circuit.

Every track is resampled to a closed centre line with points every 5 m: x, y (m), right width, left width (m).
The game's track ids follow the F1 25 UDP specification's track id appendix.

    python scripts/gen_tracks.py
"""
import csv
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TUM = os.path.join(ROOT, 'third_party', 'racetrack-database', 'tracks')
GEO = os.path.join(ROOT, 'third_party', 'f1-circuits', 'circuits')
OUT = os.path.join(ROOT, 'apps', 'dash-app', 'tracks', 'track_data.inc')
STEP = 5.0

# game track id(s) -> (Chinese name, source kind, file, default width for centre-line-only sources)
