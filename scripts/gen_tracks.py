REVERSED_IDS = {39, 40, 41}


def load_tum(name):
    pts = []
    with open(os.path.join(TUM, name + '.csv'), newline='') as f:
        for row in csv.reader(f):
            if not row or row[0].startswith('#'):
                continue
            x, y, wr, wl = (float(v) for v in row[:4])
            pts.append((x, y, wr, wl))
    return pts


def load_geo(name, width):
    d = json.load(open(os.path.join(GEO, name + '.geojson'), encoding='utf-8'))
    coords = d['features'][0]['geometry']['coordinates']
    lat0 = sum(c[1] for c in coords) / len(coords)
    lon0 = sum(c[0] for c in coords) / len(coords)
    k = 6371000.0 * math.pi / 180.0
    pts = [((c[0] - lon0) * k * math.cos(math.radians(lat0)), (c[1] - lat0) * k, width / 2, width / 2) for c in coords]
    if math.dist(pts[0][:2], pts[-1][:2]) < 1.0:
        pts.pop()
    return pts


def catmull(p0, p1, p2, p3, t):
    t2, t3 = t * t, t * t * t
    return tuple(0.5 * ((2 * b) + (-a + c) * t + (2 * a - 5 * b + 4 * c - d) * t2 + (-a + 3 * b - 3 * c + d) * t3)
                 for a, b, c, d in zip(p0, p1, p2, p3))


def densify(pts, max_seg=2.0):
    """Smooth closed curve through the points (Catmull-Rom), at most max_seg metres between samples."""
    n = len(pts)
    out = []
    for i in range(n):
        p0, p1, p2, p3 = pts[i - 1], pts[i], pts[(i + 1) % n], pts[(i + 2) % n]
        seg = math.dist(p1[:2], p2[:2])
        steps = max(1, int(math.ceil(seg / max_seg)))
        for s in range(steps):
            out.append(catmull(p0, p1, p2, p3, s / steps))
    return out


def resample(pts, step):
    """Closed polyline -> points every `step` metres along it."""
    n = len(pts)
    cum = [0.0]
    for i in range(n):
        cum.append(cum[-1] + math.dist(pts[i][:2], pts[(i + 1) % n][:2]))
    total = cum[-1]
    count = max(8, int(round(total / step)))
    step = total / count
    out, j = [], 0
    for k in range(count):
        s = k * step
        while cum[j + 1] < s:
            j += 1
        a, b = pts[j], pts[(j + 1) % n]
        t = (s - cum[j]) / max(1e-9, cum[j + 1] - cum[j])
        out.append(tuple(av + (bv - av) * t for av, bv in zip(a, b)))
    return out, total


def main():
    lines = ['// Generated by scripts/gen_tracks.py from third_party/racetrack-database (LGPL-3.0) and',
             '// third_party/f1-circuits (MIT). Do not edit: change the script and run it again.',
             '// Each track: closed centre line every ~5 m as {x, y, right width, left width}, metres.', '']
    table = []
    for i, (ids, name, kind, file, width) in enumerate(TRACKS):
        raw = load_tum(file) if kind == 'tum' else load_geo(file, width)
        pts, total = resample(densify(raw), STEP)
        var = 'TRACK_%d' % i
        lines.append('static const float %s[] = {' % var)
        for x, y, wr, wl in pts:
            lines.append('    %.2ff, %.2ff, %.2ff, %.2ff,' % (x, y, wr, wl))
        lines.append('};')
        src = 'TUMFTM racetrack-database' if kind == 'tum' else 'f1-circuits（宽度为典型值）'
        for gid in ids:
            table.append('    {%d, %s, "%s", "%s", %s, %d, %.1ff},' % (
                gid, 'true' if gid in REVERSED_IDS else 'false', name + ('（反向）' if gid in REVERSED_IDS else ''),
                src, var, len(pts), total))
        print('%-4s %-12s %-10s %5d pts %7.0f m' % (','.join(map(str, ids)), file, kind, len(pts), total))
    lines.append('')
    lines.append('static const TrackEntry TRACK_TABLE[] = {')
    lines += table
    lines.append('};')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
