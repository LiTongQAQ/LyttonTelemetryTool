"""Builds apps/dash-app/tracks/tnr_data.inc from the Track N Race maps (third_party/track-n-race, GPL-3.0, by NoGoat).

Each map is the cars' median line of one F1 25 circuit, generated by Track N Race from its own recordings, laid
out in a 1000 x 1000 view box. The map file keeps the transform from game world coordinates to the view box
((world - min) * scale + off), so the line, the sector boundaries, the DRS zones, the start
line and the speed traps are turned back into game world coordinates here.

    python scripts/gen_tnr_tracks.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'third_party', 'track-n-race', 'maps')
OUT = os.path.join(ROOT, 'apps', 'dash-app', 'tracks', 'tnr_data.inc')
# F1 25 only: the 2026 season pack's tracks (Madring) and its straight-line-mode zones are left out
SEASON_2026_TRACKS = {42}


def main():
    maps = []
    for f in os.listdir(SRC):
        if f.startswith('track_') and f.endswith('.json'):
            with open(os.path.join(SRC, f), encoding='utf-8') as fh:
                maps.append(json.load(fh))
    maps = [m for m in maps if m['track_id'] not in SEASON_2026_TRACKS]
    maps.sort(key=lambda m: m['track_id'])
    out = ['// generated by scripts/gen_tnr_tracks.py from third_party/track-n-race/maps (Track N Race by NoGoat, '
           'GPL-3.0)', '// world x, z per point; zones as start / end points', '']
    entries = []
    for m in maps:
        t = m['transform']

        def world(p):
            return ((p[0] - t['off_x']) / t['scale'] + t['min_x'], (p[1] - t['off_z']) / t['scale'] + t['min_z'])

        # the three sectors share their end points; the third ends back at the start
        pts, starts = [], []
        for s in m['sectors']:
            sp = s['points']
            starts.append(max(0, len(pts) - 1) if pts else 0)
            pts.extend(sp[1:] if pts else sp)
        if len(pts) > 2 and pts[0] == pts[-1]:
            pts.pop()
        tid = m['track_id']
        flat = ','.join('%.2f,%.2f' % world(p) for p in pts)
        out.append('static const float TNR_PTS_%d[] = {%s};' % (tid, flat))

        def zones(key, kind):
            z = []
            for zz in m.get(key) or []:
                a, b = world(zz['start']), world(zz['end'])
                z.append('{%.2f,%.2f,%.2f,%.2f,\'%s\'}' % (a[0], a[1], b[0], b[1], kind))
            return z
        zl = zones('drs_zones', 'D')
        out.append('static const TnrZoneData TNR_ZONES_%d[] = {%s};' % (tid, ','.join(zl) if zl else '{0,0,0,0,0}'))
        traps = [world(p) for p in ([m['speed_traps']] if m.get('speed_traps') and not isinstance(m['speed_traps'][0], list)
                                    else (m.get('speed_traps') or []))]
        sf = world(m['start_finish'])
        trap = traps[0] if traps else (0.0, 0.0)
        entries.append('    {%d, "%s", "%s", %d, TNR_PTS_%d, %d, %d, %d, TNR_ZONES_%d, %d, %.2f, %.2f, %d, %.2f, %.2f},' % (
            tid, m['track_name'], m['circuit_name'], int(m['track_length_m']), tid, len(pts),
            starts[1] if len(starts) > 1 else 0, starts[2] if len(starts) > 2 else 0, tid, len(zl), sf[0], sf[1],
            1 if traps else 0, trap[0], trap[1]))
    out.append('')
    out.append('static const TnrTrackData TNR_TRACKS[] = {')
    out.extend(entries)
    out.append('};')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write('\n'.join(out) + '\n')
    print(len(maps), 'tracks ->', OUT)


if __name__ == '__main__':
    main()
